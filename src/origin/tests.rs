#[test]
fn origin_same_value_at_another_tag_offset_is_traced_as_its_own_layout() -> TestResult {
    let image = Image {
        data: OTHER_OFFSET.to_vec(),
        segments: vec![Segment { va: 0x1000, offset: 0, size: OTHER_OFFSET.len() }],
        functions: vec![0x1000..0x1023, 0x1040..0x1068, 0x1080..0x108d],
        pointers: Vec::new(),
        imports: Vec::new(),
        symbols: Vec::new(),
        metadata: crate::image_format::Metadata::default(),
    };
    let mut out = Vec::new();
    let options = OriginOptions { back: 1, depth: 3, limit: 12, slice: false };
    origin(&image, "Second kind", &options, &mut out)?;
    let text = String::from_utf8(out)?;
    // For the message's layout (tag at +0) the inner store at +8 has no evidence ...
    assert!(text.contains("candidate 0x1086  in 0x1080"), "{text}");
    // ... but the input layout (tag at +8) is searched too, and there it is a site with its check.
    let site = text.find("site 0x1086  in 0x1080").ok_or("inner site")?;
    let lines: Vec<&str> = text[site..].lines().take(4).collect();
    assert!(lines[0].ends_with("[tag offset]"), "{text}");
    assert!(lines.iter().any(|l| l.contains("| ") && l.contains('7')), "{text}");
    Ok(())
}
