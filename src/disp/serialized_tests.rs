use super::run;
use crate::image::{Image, Segment};

/// A serializer passing `"frozen"` with `&self.+0x144` to one call, then writing key `"mode"`
/// and reading `+0x145` after it; another function reads `+0x146` with no key around, and a
/// third passes `&self.+0x147` to a helper that pairs it with `"tag"`.
#[test]
fn a_field_is_named_by_the_key_passed_with_it_or_just_before_it() {
    let mut data = vec![0xc3u8; 0x200];
    let code: &[u8] = &[
        0x48, 0x8d, 0x35, 0xf9, 0x00, 0x00, 0x00, // 0x1000: lea rsi, [rip+0xf9] ("frozen" at 0x1100)
        0xba, 0x06, 0x00, 0x00, 0x00, // 0x1007: mov edx, 6
        0x48, 0x8d, 0x8b, 0x44, 0x01, 0x00, 0x00, // 0x100c: lea rcx, [rbx+0x144]
        0xe8, 0x68, 0x00, 0x00, 0x00, // 0x1013: call 0x1080
        0x48, 0x8d, 0x35, 0xf1, 0x00, 0x00, 0x00, // 0x1018: lea rsi, [rip+0xf1] ("mode" at 0x1110)
        0xba, 0x04, 0x00, 0x00, 0x00, // 0x101f: mov edx, 4
        0xe8, 0x57, 0x00, 0x00, 0x00, // 0x1024: call 0x1080
        0x0f, 0xb6, 0x83, 0x45, 0x01, 0x00, 0x00, // 0x1029: movzx eax, byte [rbx+0x145]
        0xc3, // 0x1030
    ];
    data[..code.len()].copy_from_slice(code);
    data[0x40..0x47].copy_from_slice(&[0x0f, 0xb6, 0x83, 0x46, 0x01, 0x00, 0x00]); // 0x1040: movzx eax, byte [rbx+0x146]
    // A field helper: the key goes with the helper's own argument rcx.
    let helper: &[u8] = &[
        0x48, 0x8d, 0x35, 0xc9, 0x00, 0x00, 0x00, // 0x1050: lea rsi, [rip+0xc9] ("tag" at 0x1120)
        0xba, 0x03, 0x00, 0x00, 0x00, // 0x1057: mov edx, 3
        0xe9, 0x1f, 0x00, 0x00, 0x00, // 0x105c: jmp 0x1080
    ];
    data[0x50..0x50 + helper.len()].copy_from_slice(helper);
    let through_helper: &[u8] = &[
        0x48, 0x8d, 0x8b, 0x47, 0x01, 0x00, 0x00, // 0x1068: lea rcx, [rbx+0x147]
        0xe8, 0xdc, 0xff, 0xff, 0xff, // 0x106f: call 0x1050
        0xc3, // 0x1074
    ];
    data[0x68..0x68 + through_helper.len()].copy_from_slice(through_helper);
    // A helper writing the key by itself, then the value through the saved argument; the key's
    // `lea rsi` overwrites the argument register, so that call does not take the field.
    let key_then_value: &[u8] = &[
        0x48, 0x89, 0xf3, // 0x1090: mov rbx, rsi
        0x48, 0x8d, 0x35, 0x96, 0x00, 0x00, 0x00, // 0x1093: lea rsi, [rip+0x96] ("id" at 0x1130)
        0xba, 0x02, 0x00, 0x00, 0x00, // 0x109a: mov edx, 2
        0xe8, 0xdc, 0xff, 0xff, 0xff, // 0x109f: call 0x1080
        0x48, 0x89, 0xdf, // 0x10a4: mov rdi, rbx
        0xe9, 0xd4, 0xff, 0xff, 0xff, // 0x10a7: jmp 0x1080
        0x90, 0x90, 0x90, 0x90, // 0x10ac
        0x48, 0x8d, 0xb3, 0x48, 0x01, 0x00, 0x00, // 0x10b0: lea rsi, [rbx+0x148]
        0xe8, 0xd4, 0xff, 0xff, 0xff, // 0x10b7: call 0x1090
        0xc3, // 0x10bc
    ];
    data[0x90..0x90 + key_then_value.len()].copy_from_slice(key_then_value);
    // The field address made by `add` and passed through a copy (read with `--in` only).
    let added: &[u8] = &[
        0x48, 0x81, 0xc3, 0x49, 0x01, 0x00, 0x00, // 0x10c0: add rbx, 0x149
        0x48, 0x8d, 0x35, 0x72, 0x00, 0x00, 0x00, // 0x10c7: lea rsi, [rip+0x72] ("sub" at 0x1140)
        0xba, 0x03, 0x00, 0x00, 0x00, // 0x10ce: mov edx, 3
        0x48, 0x89, 0xd9, // 0x10d3: mov rcx, rbx
        0xe8, 0xa5, 0xff, 0xff, 0xff, // 0x10d6: call 0x1080
        0xc3, // 0x10db
    ];
    data[0xc0..0xc0 + added.len()].copy_from_slice(added);
    // A key call that took its field: the next field read is not that key's value (review of #209).
    let field_then_read: &[u8] = &[
        0x48, 0x8d, 0x35, 0x19, 0x00, 0x00, 0x00, // 0x10e0: lea rsi, [rip+0x19] ("frozen" at 0x1100)
        0xba, 0x06, 0x00, 0x00, 0x00, // 0x10e7: mov edx, 6
        0x48, 0x8d, 0x8b, 0x4a, 0x01, 0x00, 0x00, // 0x10ec: lea rcx, [rbx+0x14a]
        0xe8, 0x88, 0xff, 0xff, 0xff, // 0x10f3: call 0x1080
        0x0f, 0xb6, 0x83, 0x4b, 0x01, 0x00, 0x00, // 0x10f8: movzx eax, byte [rbx+0x14b]
        0xc3, // 0x10ff
    ];
    data[0xe0..0xe0 + field_then_read.len()].copy_from_slice(field_then_read);
    data[0x140..0x143].copy_from_slice(b"sub");
    data[0x100..0x106].copy_from_slice(b"frozen");
    data[0x110..0x114].copy_from_slice(b"mode");
    data[0x120..0x123].copy_from_slice(b"tag");
    data[0x130..0x132].copy_from_slice(b"id");
    let image = Image {
        data,
        segments: vec![Segment { va: 0x1000, offset: 0, size: 0x200 }],
        functions: vec![
            0x1000..0x1031,
            0x1040..0x1048,
            0x1050..0x1061,
            0x1068..0x1075,
            0x1080..0x1081,
            0x1090..0x10ac,
            0x10b0..0x10bd,
            0x10e0..0x1100,
        ],
        ..Image::default()
    };
    let mut out = Vec::new();
    let offsets = [0x144, 0x145, 0x146, 0x147, 0x148, 0x14a, 0x14b];
    assert!(run(&image, &image.functions, &offsets, &mut out).is_ok());
    let text = String::from_utf8_lossy(&out);
    assert!(text.contains("+0x144  \"frozen\"\n  \"frozen\"  in 0x1000  call 0x1013 -> "), "{text}");
    assert!(text.contains("[rbx+0x144])"), "{text}");
    assert!(text.contains("+0x145  \"mode\"\n  \"mode\"  in 0x1000  0x1029  movzx"), "{text}");
    assert!(text.contains("(after the key call)"), "{text}");
    assert!(text.contains("+0x146  not serialized: 1 functions access it"), "{text}");
    assert!(text.contains("+0x147  \"tag\"\n  \"tag\"  in 0x1068  call 0x106f -> "), "{text}");
    assert!(text.contains("+0x148  \"id\"\n  \"id\"  in 0x10b0  call 0x10b7 -> "), "{text}");
    assert!(text.contains("+0x14a  \"frozen\"\n  \"frozen\"  in 0x10e0  call 0x10f3 -> "), "{text}");
    assert!(text.contains("+0x14b  not serialized: 1 functions access it"), "{text}");
    // The key call's own field argument is not also reported as read after the previous key.
    assert_eq!(text.matches("after the key call").count(), 1, "{text}");
    let mut out = Vec::new();
    assert!(run(&image, std::slice::from_ref(&(0x10c0..0x10dc)), &[0x149], &mut out).is_ok());
    let text = String::from_utf8_lossy(&out);
    assert!(text.starts_with("+0x149  \"sub\"\n  \"sub\"  in 0x10c0  call 0x10d6 -> "), "{text}");
    assert!(text.contains("(add rbx, 0x149)"), "{text}");
}
