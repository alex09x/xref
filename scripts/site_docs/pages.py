def sidebar(meta, current):
    out = ['        <nav class="doc-nav" aria-label="Documentation">',
           f'          <a class="doc-nav-home{" is-current" if current is None else ""}" href="/docs/">Overview</a>']
    for group in dict.fromkeys(g for g, *_ in meta):
        out.append(f'          <div class="side-group-lbl">{html.escape(group)}</div>')
        for g, name, title, _ in meta:
            if g == group:
                attr = ' aria-current="page" class="is-current"' if name == current else ""
                out.append(f'          <a href="/docs/{name}"{attr}>{html.escape(title)}</a>')
    out.append('          <div class="side-group-lbl">Walkthroughs</div>')
    out.append('          <a href="/live-walkthrough">Live Analysis walkthrough</a>')
    out.append("        </nav>")
    return "\n".join(out)


def page_html(name, title, summary, body, toc, meta):
    head = HEAD.format(generated=GENERATED.format(src=f"{name}.md"), title=html.escape(title),
                       summary=html.escape(summary), path=f"/docs/{name}")
    on_page = ""
    if toc:
        items = "\n".join(f'            <li class="toc-l{lvl}"><a href="#{a}">{html.escape(t)}</a></li>' for lvl, a, t in toc)
        on_page = f'        <details class="doc-toc" open><summary>On this page</summary>\n          <ol>\n{items}\n          </ol>\n        </details>\n'
    source = f"https://github.com/alex09x/xref/blob/main/docs/{name}.md"
    return "\n".join([
        head,
        '    <main class="wrap doc-layout" id="top">',
        sidebar(meta, name),
        '      <article class="doc-body">',
        f"        <h1>{html.escape(title)}</h1>",
        on_page + body,
        f'        <p class="doc-source">Source: <a href="{source}" rel="noopener">docs/{name}.md</a> · '
        "generated for the site; edit the Markdown, not this page.</p>",
        "      </article>",
        "    </main>",
        FOOTER,
    ])


def index_html(meta):
    head = HEAD.format(generated=GENERATED.format(src="*.md"), title="Documentation",
                       summary="XRef guides: serialized field search, cross-build matching, investigations, live process "
                               "analysis, call traces, profiles and the local MCP server.",
                       path="/docs/")
    cards = []
    for group in dict.fromkeys(g for g, *_ in meta):
        cards.append(f'        <h2 class="doc-group">{html.escape(group)}</h2>\n        <div class="grid-3">')
        for g, name, title, summary in meta:
            if g == group:
                cards.append(f'          <a class="card doc-card" href="/docs/{name}"><h3>{html.escape(title)}</h3>'
                             f"<p>{html.escape(summary)}</p></a>")
        cards.append("        </div>")
    return "\n".join([
        head,
        '    <main class="wrap doc-layout" id="top">',
        sidebar(meta, None),
        '      <article class="doc-body">',
        "        <h1>Documentation</h1>",
        '        <p class="hero-sub">Guides for every XRef workflow, generated from the Markdown in the repository. '
        'Start with the <a href="/#cli">command reference</a> on the home page, or the recorded '
        '<a href="/live-walkthrough">Live Analysis walkthrough</a>.</p>',
        *cards,
        "      </article>",
        "    </main>",
        FOOTER,
    ])
