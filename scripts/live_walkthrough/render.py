"""Render a transcript from `record.py` into docs/live-walkthrough.md and docs/live-walkthrough.html.

Recorded stdout/stderr is copied unchanged; only the surrounding prose is generated."""

import argparse
import html
import json
import os
import re
import shlex

from page import FOOTER, HEAD, INTRO, PRIVILEGES, REPRODUCE, STATUS, TOPBAR, AGENT
from steps import sections

_INLINE = re.compile(r"\[([^\]]+)\]\(([^)]+)\)|`([^`]+)`")


def inline_html(text):
    out, pos = [], 0
    for m in _INLINE.finditer(text):
        out.append(html.escape(text[pos:m.start()]))
        if m.group(1) is not None:
            out.append(f'<a href="{html.escape(m.group(2))}">{inline_html(m.group(1))}</a>')
        else:
            out.append(f"<code>{html.escape(m.group(3))}</code>")
        pos = m.end()
    out.append(html.escape(text[pos:]))
    return "".join(out)


def receipts(stderr):
    """Lines xref wrote to stderr (timings and `*_ready` receipts)."""
    return "\n".join(line for line in stderr.splitlines() if line.startswith("xref: "))


def trim(text):
    """Drop trailing spaces at line ends (the transcript JSON keeps them); nothing else changes."""
    return "\n".join(line.rstrip(" ") for line in text.rstrip("\n").split("\n"))


def run_parts(doc, sec):
    if "terminal" in sec:
        return {"cmd": None, "io": sec["terminal"], "stdout": None, "stderr": ""}
    step = next(s for s in doc["steps"] if s["id"] == sec["step"])
    io = [(f"> {e['send']}", e["reply"]) for e in step["daemon_io"]]
    return {"cmd": shlex.join(step["argv"]), "io": io, "stdout": trim(step["stdout"]),
            "stderr": receipts(step["stderr"])}


def provenance(meta, pid):
    return [
        ("xref", f"{meta['xref_version']} built from main at {meta['xref_commit']} (release), sha256 {meta['xref_sha256']}"),
        ("Toolchain", meta["rustc"]),
        ("Host", f"development {meta['kernel']} host, recorded {meta['recorded_utc']}"),
        ("Fixture", f"{meta['fixture_build']}; source sha256 {meta['fixture_source_sha256']}; binary sha256 {meta['fixture_sha256']}"),
        ("Run", f"daemon PID {pid}. PIDs and runtime addresses belong to this run; ASLR changes them on every start."),
        ("Output", "stdout and stderr are copied unchanged except that spaces at line ends are trimmed; "
                   "scripts/live_walkthrough/transcript.json keeps the raw capture."),
    ]


def render_md(doc, secs):
    out = ["<!-- Generated by scripts/live_walkthrough/render.py from a recorded transcript. Do not edit by hand. -->", "",
           "# Live Analysis walkthrough", "", "> [!NOTE]", f"> {STATUS.format(version=doc['meta']['xref_version'])}", "",
           INTRO, "",
           "Also on the site: [xrefcode.com/live-walkthrough](https://xrefcode.com/live-walkthrough). "
           "Contract and limits: [live.md](live.md).", "", "## Contents", ""]
    out += [f"{i}. [{s['title']}](#{i}-{slug(s['title'])})" for i, s in enumerate(secs, 1)]
    out += ["", "## Provenance", ""] + [f"- **{k}:** {v}" if k in ("Run", "Output") else f"- **{k}:** `{v}`"
                                         for k, v in provenance(doc["meta"], doc["pid"])]
    out += ["", "## Privileges", "", PRIVILEGES, "", "## Reproduce", "", "```console", REPRODUCE, "```", ""]
    for i, sec in enumerate(secs, 1):
        parts = run_parts(doc, sec)
        out += [f"## {i}. {sec['title']}", ""] + sum(([p, ""] for p in sec["lead"]), [])
        if sec.get("sudo"):
            out += ["Recorded with `sudo -n` (privileged perf access), against the fixture only.", ""]
        if parts["cmd"]:
            out += ["```console", f"$ {parts['cmd']}", "```", ""]
        if parts["io"]:
            label = "Daemon session:" if parts["cmd"] is None else "Sent to the daemon while the observer was armed:"
            out += [label, "", "```text"] + [f"{a}\n{b}" for a, b in parts["io"]]
            out += ["```", ""]
        if parts["stdout"] is not None:
            out += ["Recorded stdout:", "", "```text", parts["stdout"], "```", ""]
        if parts["stderr"]:
            out += ["stderr:", "", "```text", parts["stderr"], "```", ""]
        if sec.get("notes"):
            out += ["What it shows:", ""] + [f"- {n}" for n in sec["notes"]] + [""]
    out += ["## Use it from an agent", "", AGENT, ""]
    return "\n".join(out)


def slug(title):
    return re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")


def render_html(doc, secs):
    pre = lambda cls, text: f'<pre class="code-view {cls}">{html.escape(text)}</pre>'  # noqa: E731
    recorded = html.escape(doc["meta"]["xref_version"])  # e.g. "xref 0.4.0", checked by scripts/check_versions.py
    body = [HEAD, TOPBAR, '    <main class="wrap" id="top">', '      <section class="hero">',
            f'        <div class="eyebrow">Recorded with {recorded} · Linux x86-64</div>',
            "        <h1>Live Analysis: from a running process to the code that writes its memory.</h1>",
            f'        <p class="hero-sub">{inline_html(INTRO)}</p>',
            f'        <div class="lw-status"><span class="pill pill-demo">{recorded.replace("xref ", "v")}</span> '
            f'{inline_html(STATUS.format(version=doc["meta"]["xref_version"]))}</div>',
            '        <ol class="lw-toc">']
    body += [f'          <li><a href="#step-{s["id"]}">{inline_html(s["title"])}</a></li>' for s in secs]
    body += ["        </ol>", '        <div class="prov-box"><strong>Provenance.</strong><ul class="lw-prov">']
    body += [f"          <li><strong>{k}:</strong> <code>{html.escape(v)}</code></li>" for k, v in provenance(doc["meta"], doc["pid"])]
    body += ["        </ul></div>",
             f'        <div class="prov-box"><strong>Privileges.</strong> {inline_html(PRIVILEGES)}</div>',
             '        <div class="prov-box"><strong>Reproduce</strong> from a checkout of <code>main</code> on Linux x86-64:'
             f'<pre class="cli-box lw-repro">{html.escape(REPRODUCE)}</pre></div>', "      </section>"]
    for i, sec in enumerate(secs, 1):
        parts = run_parts(doc, sec)
        badge = "recorded with sudo -n · fixture only" if sec.get("sudo") else "unprivileged"
        body += [f'      <section class="section lw-step" id="step-{sec["id"]}">',
                 f'        <div class="section-head"><h2>{i}. {inline_html(sec["title"])}</h2>'
                 f'<span class="section-note">{badge}</span></div>']
        body += [f'        <p class="lw-lead">{inline_html(p)}</p>' for p in sec["lead"]]
        body.append('        <div class="workbench lw-run">')
        if parts["cmd"]:
            body.append(f'          <div class="cmd-bar"><div class="cmd-text"><span class="cmd-prompt">$</span>'
                        f'<code>{html.escape(parts["cmd"])}</code></div></div>')
        if parts["io"]:
            label = "DAEMON SESSION" if parts["cmd"] is None else "SENT TO THE DAEMON WHILE THE OBSERVER WAS ARMED"
            body.append(f'          <div class="recorded-meta-bar"><span>{label}</span></div>')
            body.append("          " + pre("lw-io", "\n".join(f"{a}\n{b}" for a, b in parts["io"])))
        if parts["stdout"] is not None:
            body.append('          <div class="recorded-meta-bar"><span>RECORDED STDOUT</span><span>exit 0</span></div>')
            body.append("          " + pre("lw-out", parts["stdout"]))
        if parts["stderr"]:
            body.append('          <div class="recorded-meta-bar"><span>STDERR</span></div>')
            body.append("          " + pre("lw-err", parts["stderr"]))
        body.append("        </div>")
        if sec.get("notes"):
            body += ['        <ul class="lw-notes">'] + [f"          <li>{inline_html(n)}</li>" for n in sec["notes"]] + ["        </ul>"]
        body.append("      </section>")
    body += ['      <section class="section" id="agent">', '        <div class="section-head"><h2>Use it from an agent</h2></div>',
             f'        <p class="lw-lead">{inline_html(AGENT)}</p>', "      </section>", "    </main>", FOOTER]
    return "\n".join(body) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("transcript")
    ap.add_argument("--docs", default=os.path.join(os.path.dirname(__file__), "..", "..", "docs"))
    args = ap.parse_args()
    with open(args.transcript, encoding="utf-8") as fh:
        doc = json.load(fh)
    secs = sections(doc)
    for name, text in (("live-walkthrough.md", render_md(doc, secs)), ("live-walkthrough.html", render_html(doc, secs))):
        path = os.path.normpath(os.path.join(args.docs, name))
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text if text.endswith("\n") else text + "\n")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
